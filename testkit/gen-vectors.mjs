const sourceOf = (vectors) => `// Generated by testkit/gen-vectors.mjs with node:crypto, independently of src/public/js/core/.
// Committed on purpose: never regenerate this file to make a failing test pass. A change here is a
// change of the on-disk format (docs/03 §2) and needs a written reason.
export const VECTORS = ${JSON.stringify(vectors, null, 2)};
`;

if (process.argv.includes('--write')) {
  await writeFile(OUT, sourceOf(VECTORS));
  console.log(`wrote ${OUT.pathname}`);
} else {
  process.exit(await compareWithCommitted() ? 0 : 1);
}

// gzip output differs between zlib builds (Node 24 on macOS vs the machine that generated the file),
// so vaultGzip and envelope.ct are checked in layers. Every other key is compared byte for byte.
async function compareWithCommitted() {
  const text = (await readFile(OUT, 'utf8').catch(() => '')).replace(/\r\n/g, '\n');
  const report = (ok, what) => {
    console.log(`${ok ? 'ok      ' : 'DIFFERS '} ${what}`);
    return ok;
  };
  const start = text.indexOf('export const VECTORS = ');
  if (start < 0) return report(false, 'testkit/vectors.js is missing or has no VECTORS');
  const committed = JSON.parse(text.slice(start + 'export const VECTORS = '.length).replace(/;\s*$/, ''));
  const gz = Buffer.from(committed.vaultGzip, 'base64');
  let gunzipped = null;
  try {
    gunzipped = gunzipSync(gz).toString('utf8');
  } catch {
    // Reported below: a vaultGzip that does not gunzip cannot equal the vault.
  }
  const layer1 = report(gunzipped === JSON.stringify(vault), 'vaultGzip gunzips to inputs.vault');
  const ct = gcm(vaultKey, iv.vault, gz, `keymesh/v2/vault/${vaultId}`);
  const layer2 = report(b64(ct) === committed.envelope.ct, 'envelope.ct is AES-GCM over the committed vaultGzip');
  // The only two values allowed to differ from a fresh run are put back; the file must then match.
  VECTORS.vaultGzip = committed.vaultGzip;
  VECTORS.envelope.ct = committed.envelope.ct;
  const rest = report(text === sourceOf(VECTORS), 'every other key and the file header match node:crypto byte for byte');
  return layer1 && layer2 && rest;
}
